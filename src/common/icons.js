/**
 * Resolve the appropriate icon string based on file extension and directory status
 */
export function getFileIcon(filename, isDirectory = false, isParent = false) {
  if (isParent) return ICONS.folderParent;
  if (isDirectory) return ICONS.folder;

  const ext = (filename.split('.').pop() || '').toLowerCase();
  
  // Image extensions
  if (['png', 'jpg', 'jpeg', 'webp', 'gif', 'svg', 'bmp', 'ico', 'avif', 'tiff'].includes(ext)) {
    return ICONS.image;
  }
  // Video extensions
  if (['mp4', 'mkv', 'webm', 'mov', 'avi', 'wmv', 'flv', 'm4v'].includes(ext)) {
    return ICONS.video;
  }
  // Audio extensions
  if (['mp3', 'wav', 'ogg', 'flac', 'm4a', 'aac', 'wma', 'opus'].includes(ext)) {
    return ICONS.audio;
  }
  // Markdown & docs
  if (['md', 'markdown', 'mdx', 'mdown'].includes(ext)) {
    return ICONS.markdown;
  }
  // PDF
  if (ext === 'pdf') {
    return ICONS.pdf;
  }
  // JSON & Data
  if (['json', 'json5', 'jsonc', 'geojson'].includes(ext)) {
    return ICONS.json;
  }
  // Archives
  if (['zip', 'tar', 'gz', 'bz2', 'xz', '7z', 'rar', 'iso', 'zst'].includes(ext)) {
    return ICONS.archive;
  }
  // Code
  if (['js', 'mjs', 'cjs', 'ts', 'tsx', 'jsx', 'py', 'pyw', 'rs', 'go', 'html', 'htm', 'css', 'scss', 'sass', 'less', 'c', 'cpp', 'h', 'hpp', 'java', 'kt', 'cs', 'php', 'rb', 'sh', 'bash', 'ps1', 'bat', 'cmd', 'yaml', 'yml', 'toml', 'ini', 'sql', 'xml', 'dockerfile', 'lua', 'zig'].includes(ext)) {
    return ICONS.code;
  }

  return ICONS.file;
}
