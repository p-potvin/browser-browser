/**
 * Resolve Catppuccin icon for given filename / folder
 */
export function getCatppuccinIcon(filename, isDirectory = false, isParent = false) {
  if (isParent) return CATPPUCCIN_ICONS.folderParent;
  
  if (isDirectory) {
    const lower = (filename || '').toLowerCase();
    if (lower.includes('git') || lower.includes('repo')) return CATPPUCCIN_ICONS.folderGit;
    if (lower.includes('download')) return CATPPUCCIN_ICONS.folderDownload;
    if (lower.includes('desktop')) return CATPPUCCIN_ICONS.folderDesktop;
    if (lower.includes('image') || lower.includes('photo') || lower.includes('picture')) return CATPPUCCIN_ICONS.folderImages;
    if (lower.includes('music') || lower.includes('audio') || lower.includes('sound')) return CATPPUCCIN_ICONS.folderMusic;
    return CATPPUCCIN_ICONS.folder;
  }

  const ext = (filename.split('.').pop() || '').toLowerCase();
  
  if (['js', 'mjs', 'cjs', 'jsx'].includes(ext)) return CATPPUCCIN_ICONS.javascript;
  if (['ts', 'tsx', 'mts', 'cts'].includes(ext)) return CATPPUCCIN_ICONS.typescript;
  if (['py', 'pyw', 'ipynb'].includes(ext)) return CATPPUCCIN_ICONS.python;
  if (['rs'].includes(ext)) return CATPPUCCIN_ICONS.rust;
  if (['go'].includes(ext)) return CATPPUCCIN_ICONS.go;
  if (['html', 'htm'].includes(ext)) return CATPPUCCIN_ICONS.html;
  if (['css', 'scss', 'sass', 'less'].includes(ext)) return CATPPUCCIN_ICONS.css;
  if (['json', 'json5', 'jsonc', 'geojson'].includes(ext)) return CATPPUCCIN_ICONS.json;
  if (['md', 'markdown', 'mdx'].includes(ext)) return CATPPUCCIN_ICONS.markdown;
  if (['png', 'jpg', 'jpeg', 'webp', 'gif', 'svg', 'bmp', 'ico', 'avif'].includes(ext)) return CATPPUCCIN_ICONS.image;
  if (['mp4', 'mkv', 'webm', 'mov', 'avi', 'wmv'].includes(ext)) return CATPPUCCIN_ICONS.video;
  if (['mp3', 'wav', 'ogg', 'flac', 'm4a', 'aac', 'opus'].includes(ext)) return CATPPUCCIN_ICONS.audio;
  if (['pdf'].includes(ext)) return CATPPUCCIN_ICONS.pdf;
  if (['zip', 'tar', 'gz', 'bz2', 'xz', '7z', 'rar', 'iso', 'zst'].includes(ext)) return CATPPUCCIN_ICONS.archive;
  if (['c', 'cpp', 'h', 'hpp', 'cs', 'java', 'kt', 'php', 'rb', 'sh', 'bash', 'ps1', 'bat', 'cmd', 'yaml', 'yml', 'toml', 'sql', 'dockerfile', 'lua', 'zig'].includes(ext)) {
    return CATPPUCCIN_ICONS.code;
  }

  return CATPPUCCIN_ICONS.file;
}
